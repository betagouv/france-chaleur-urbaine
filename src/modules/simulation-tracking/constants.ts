import { z } from 'zod';

import { ESPACE_EXTERIEUR_VALUES, TYPE_LOGEMENT_VALUES, TYPE_RADIATEUR_VALUES } from '@/modules/chaleur-renouvelable/constants';

/**
 * Constants and Zod schemas of the `simulation-tracking` module. The simulator value lists are imported from
 * `chaleur-renouvelable/constants` only (never its client or server code): see `AGENTS.md`.
 */
/** Outcome of a simulation, recorded by the client after the server confirmed the demand (or on the France Rénov' click). */
export const SIMULATION_OUTCOME_VALUES = ['heat_network_demand', 'ccrt_demand', 'france_renov_orientation'] as const;
export type SimulationOutcome = (typeof SIMULATION_OUTCOME_VALUES)[number];

/** Current state of a simulation as shown to the user: inputs and the contact options that were offered. */
const zSimulationSnapshot = z.object({
  address: z.string().trim().min(1).max(500).nullable(),
  /** A BAN house number matched the address; otherwise the results were computed without any address context. */
  addressResolved: z.boolean(),
  batimentConstructionId: z.string().trim().min(1).max(100).nullable(),
  /** The dedicated CCRT accompaniment form was available (covered territory + collective heating). */
  ccrtDemandAvailable: z.boolean(),
  communeCode: z.string().trim().min(1).max(5).nullable(),
  departementCode: z.string().trim().min(1).max(3).nullable(),
  /** The heat network solution and its demand form were offered. */
  heatNetworkAvailable: z.boolean(),
  housingType: z.enum(TYPE_LOGEMENT_VALUES),
  outdoorSpace: z.enum(ESPACE_EXTERIEUR_VALUES).nullable(),
  radiatorType: z.enum(TYPE_RADIATEUR_VALUES).nullable(),
  /** Catalogue id of the first displayed solution; `null` when no solution fits. */
  recommendedSolution: z.string().trim().min(1).max(100).nullable(),
  /** Arrived from the "connection not feasible" email: the heat network is withdrawn from the solutions. */
  refusalAlreadyKnown: z.boolean(),
});
export type SimulationSnapshot = z.infer<typeof zSimulationSnapshot>;

/** Page the simulation was started from (form submit), with the conversion attribution of that page. */
export const zSimulationStart = z.object({
  /** Best-effort embedding page (conversion-tracking `host`). */
  host: z.string().trim().min(1).max(2000).nullable(),
  /** Exact pathname of the start page. */
  page: z.string().trim().min(1).max(2000),
  /** Next route pattern of the start page (`/`, `/chaleur-renouvelable`, or the results page on a direct arrival). */
  route: z.string().trim().min(1).max(2000),
  /** Iframe integration id (`?source=`), from the conversion-tracking registry. */
  source: z.string().trim().min(1).max(100).nullable(),
});
export type SimulationStart = z.infer<typeof zSimulationStart>;

export const zCreateSimulation = zSimulationSnapshot.extend(zSimulationStart.shape).extend({
  /** Generated by the client (uuid v4): it is also the write secret of the later updates. */
  id: z.uuid(),
  /** Simulation shown before this one on the same results page (address or building changed), `null` for the first. */
  previousSimulationId: z.uuid().nullable(),
});
export type CreateSimulationInput = z.infer<typeof zCreateSimulation>;

export const zUpdateSimulation = zSimulationSnapshot.extend({ id: z.uuid() });
export type UpdateSimulationInput = z.infer<typeof zUpdateSimulation>;

/** A demand created by the server: its id links the simulation to the demand tables (reconciliation). */
const zDemandOutcome = z.object({
  /** Id of the created row: `demands` for `heat_network_demand`, `demands_chaleur_renouvelable` for `ccrt_demand`. */
  demandId: z.string().trim().min(1).max(100),
  outcome: z.enum(SIMULATION_OUTCOME_VALUES).exclude(['france_renov_orientation']),
});
const zOrientationOutcome = z.object({ outcome: z.literal('france_renov_orientation') });
/** Outcome declared by the client: a demand carries its id, the France Rénov' orientation has none. */
export const zSimulationOutcomeDeclaration = z.discriminatedUnion('outcome', [zDemandOutcome, zOrientationOutcome]);
export type SimulationOutcomeDeclaration = z.infer<typeof zSimulationOutcomeDeclaration>;

export const zRecordSimulationOutcome = z.discriminatedUnion('outcome', [
  zDemandOutcome.extend({ id: z.uuid() }),
  zOrientationOutcome.extend({ id: z.uuid() }),
]);
export type RecordSimulationOutcomeInput = z.infer<typeof zRecordSimulationOutcome>;

/** Admin funnel of the simulations: period plus optional filters on the simulation inputs. */
export const zGetSimulationFunnel = z.object({
  dateFrom: z.coerce.date(),
  dateTo: z.coerce.date(),
  departementCode: z.string().trim().min(1).max(3).optional(),
  housingType: z.enum(TYPE_LOGEMENT_VALUES).optional(),
  outdoorSpace: z.enum(ESPACE_EXTERIEUR_VALUES).optional(),
  radiatorType: z.enum(TYPE_RADIATEUR_VALUES).optional(),
});
export type GetSimulationFunnelInput = z.infer<typeof zGetSimulationFunnel>;
