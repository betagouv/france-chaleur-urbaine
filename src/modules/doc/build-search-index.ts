import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

import { type DocSearchDocument, extractPlainText } from './search-extract';

const contentDir = resolve(process.cwd(), 'src/modules/doc/content');
const outFile = resolve(process.cwd(), 'src/modules/doc/search-index.generated.ts');

/**
 * Generates the doc search index (`search-index.generated.ts`, gitignored) from the MDX content.
 * Standalone script (`pnpm doc:build-search-index`): no CLI, no env, no database, so it stays
 * cheap to run from the `postinstall`, `predev` and `prebuild` hooks.
 */
async function main() {
  const files = (await readdir(contentDir)).filter((file) => file.endsWith('.mdx')).sort();
  const documents: DocSearchDocument[] = await Promise.all(
    files.map(async (file) => {
      const raw = await readFile(`${contentDir}/${file}`, 'utf8');
      const slug = file.replace(/\.mdx$/, '');
      const title = (raw.match(/^#\s+(.+)$/m)?.[1] ?? slug).trim();
      return { slug, text: extractPlainText(raw), title };
    })
  );

  await writeFile(
    outFile,
    `// Generated by \`pnpm doc:build-search-index\` (postinstall, predev, prebuild) — not versioned, do not edit.
import type { DocSearchDocument } from './search-extract';

export const docSearchDocuments: DocSearchDocument[] = ${JSON.stringify(documents)};
`
  );
}

main();
